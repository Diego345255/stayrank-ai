function getCurrentLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && TRANSLATIONS[saved]) return saved;
  } catch {
    // localStorage unavailable - fall through to default
  }
  return "en";
}

// Falls back to English, then to the raw key itself, so a missing
// translation never renders as a blank string or "undefined".
function t(key) {
  const lang = getCurrentLang();
  return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? key;
}

function applyTranslations() {
  const lang = getCurrentLang();
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  // A small, deliberately separate set from data-i18n above: only for
  // static, developer-authored strings (never external/user data) that
  // need an embedded <strong> lead-in - e.g. the trust-list items. Safe to
  // use innerHTML here specifically because these values only ever come
  // from the TRANSLATIONS table above, never from hotel/review/API data.
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.dataset.i18nTitle));
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  });
}

function setLang(lang) {
  if (!TRANSLATIONS[lang]) return;
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    // Non-fatal - the switch still works for this page view.
  }
  applyTranslations();
  // app.js defines this once the DOM/state are ready - re-renders any
  // already-rendered dynamic content (hotel card buttons, etc.) that also
  // uses t(), so switching language updates the whole visible page, not
  // just the static shell, without requiring a fresh search.
  if (typeof window.onLanguageChanged === "function") {
    window.onLanguageChanged();
  }
}

function initLanguageSelect() {
  const select = document.getElementById("languageSelect");
  if (!select) return;
  select.innerHTML = SUPPORTED_LANGS.map(
    (lang) => `<option value="${lang.code}">${lang.label}</option>`
  ).join("");
  select.value = getCurrentLang();
  select.addEventListener("change", () => setLang(select.value));
}

// Runs synchronously, before any CSS paints, mirroring index.html's own
// inline dark-mode script - the static shell should never flash English
// then switch to the saved language.
applyTranslations();
initLanguageSelect();
